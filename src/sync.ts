import { PLAYLIST_MARKER } from './config';
import type { Store } from './library';
import { ApiError, type SpotifyClient } from './spotify';

/**
 * Safety model: the app only ever modifies a playlist when ALL hold:
 *   1. its id is in the local registry (or it carries our description marker AND our name, for recovery),
 *   2. it is owned by the current user,
 *   3. its description, when Spotify returns one, still contains the marker.
 * Playlists you made yourself are never touched.
 */

export interface Desired { key: string; name: string; uris: string[] }
export interface PlanItem {
  key: string; name: string;
  action: 'create' | 'update' | 'skip';
  playlistId?: string;
  adopted?: boolean;       // matched an existing marked playlist (registry was lost)
  add: string[]; remove: string[]; unchanged: number;
  reason?: string;         // why it was skipped
}
export interface Orphan { key: string; name: string; playlistId: string }
export interface Plan { items: PlanItem[]; orphans: Orphan[] }

interface PlaylistObj { id: string; name: string; description?: string | null; owner: { id: string } }
interface Page<T> { items: T[]; next: string | null }
interface PlaylistItem { item?: { uri?: string } | null; track?: { uri?: string } | null }

const DESCRIPTION = `${PLAYLIST_MARKER} Generated by Genre Playlists. Changes made here are overwritten on the next sync.`;
const CHUNK = 100;

async function allPages<T>(api: SpotifyClient, first: string): Promise<T[]> {
  const out: T[] = [];
  for (let url: string | null = first; url;) {
    const p: Page<T> = await api.get<Page<T>>(url);
    out.push(...p.items);
    url = p.next;
  }
  return out;
}

const chunks = <T>(a: T[], n: number): T[][] => Array.from({ length: Math.ceil(a.length / n) }, (_, i) => a.slice(i * n, i * n + n));

function problem(pl: PlaylistObj, meId: string): string | null {
  if (pl.owner.id !== meId) return 'not owned by you';
  if (pl.description != null && !pl.description.includes(PLAYLIST_MARKER)) return 'its marker was removed from the description';
  return null;
}

async function getPlaylist(api: SpotifyClient, id: string): Promise<PlaylistObj | null> {
  try {
    return await api.get<PlaylistObj>(`/playlists/${id}`);
  } catch (e) {
    if (e instanceof ApiError && (e.status === 404 || e.status === 403)) return null; // deleted / unfollowed
    throw e;
  }
}

async function currentUris(api: SpotifyClient, id: string): Promise<string[]> {
  const rows = await allPages<PlaylistItem>(api, `/playlists/${id}/items?limit=50`);
  return rows.map((r) => (r.item ?? r.track)?.uri).filter((u): u is string => !!u);
}

/** Dry run: reads from Spotify but changes nothing. */
export async function buildPlan(api: SpotifyClient, store: Store, desired: Desired[], meId: string): Promise<Plan> {
  const registry = new Map((await store.registry()).map((e) => [e.key, e]));
  let marked: Map<string, string> | null = null; // name -> playlist id, for recovery after a data wipe
  const loadMarked = async () => {
    const all = await allPages<PlaylistObj>(api, '/me/playlists?limit=50');
    const m = new Map<string, string>();
    for (const p of all) if (p.owner.id === meId && p.description?.includes(PLAYLIST_MARKER) && !m.has(p.name)) m.set(p.name, p.id);
    return m;
  };

  const items: PlanItem[] = [];
  for (const d of desired) {
    const base = { key: d.key, name: d.name };
    let id = registry.get(d.key)?.playlistId;
    let pl: PlaylistObj | null = id ? await getPlaylist(api, id) : null;
    let adopted = false;
    if (!pl) {
      marked ??= await loadMarked();
      const m = marked.get(d.name);
      if (m) { pl = await getPlaylist(api, m); id = m; adopted = !!pl; }
    }
    if (!pl || !id) {
      items.push({ ...base, action: 'create', add: d.uris, remove: [], unchanged: 0 });
      continue;
    }
    const why = problem(pl, meId);
    if (why) { items.push({ ...base, action: 'skip', playlistId: id, add: [], remove: [], unchanged: 0, reason: why }); continue; }
    const have = new Set(await currentUris(api, id));
    const want = new Set(d.uris);
    const add = d.uris.filter((u) => !have.has(u));
    const remove = [...have].filter((u) => !want.has(u));
    items.push({ ...base, action: 'update', playlistId: id, adopted, add, remove, unchanged: d.uris.length - add.length });
  }

  const desiredKeys = new Set(desired.map((d) => d.key));
  const orphans = [...registry.values()].filter((e) => !desiredKeys.has(e.key)).map(({ key, name, playlistId }) => ({ key, name, playlistId }));
  return { items, orphans };
}

export interface ApplyProgress { done: number; total: number; current: string }

export async function applyPlan(
  api: SpotifyClient,
  store: Store,
  plan: Plan,
  onProgress: (p: ApplyProgress) => void,
): Promise<{ created: number; updated: number; skipped: number }> {
  const todo = plan.items.filter((i) => i.action !== 'skip');
  const stats = { created: 0, updated: 0, skipped: plan.items.length - todo.length };
  let done = 0;
  for (const it of todo) {
    onProgress({ done, total: todo.length, current: it.name });
    let id = it.playlistId;
    if (it.action === 'create') {
      const pl = await api.post<{ id: string }>('/me/playlists', { name: it.name, description: DESCRIPTION, public: false });
      id = pl.id;
      await store.putRegistry({ key: it.key, playlistId: id, name: it.name }); // register first: a crash must not leak untracked playlists
      stats.created++;
    } else {
      if (it.adopted) await store.putRegistry({ key: it.key, playlistId: id!, name: it.name });
      stats.updated++;
    }
    for (const c of chunks(it.remove, CHUNK)) await api.del(`/playlists/${id}/items`, { items: c.map((uri) => ({ uri })) });
    for (const c of chunks(it.add, CHUNK)) await api.post(`/playlists/${id}/items`, { uris: c });
    done++;
  }
  onProgress({ done, total: todo.length, current: '' });
  return stats;
}

/** Deletes (unfollows) generated playlists that are no longer wanted. Verified one by one; never touches anything else. */
export async function removeOrphans(api: SpotifyClient, store: Store, orphans: Orphan[], meId: string): Promise<string[]> {
  const log: string[] = [];
  for (const o of orphans) {
    const pl = await getPlaylist(api, o.playlistId);
    if (!pl) { await store.deleteRegistry(o.key); log.push(`${o.name}: already gone`); continue; }
    const why = problem(pl, meId);
    if (why) { log.push(`${o.name}: left alone (${why})`); continue; }
    await api.del(`/me/library?uris=${encodeURIComponent(`spotify:playlist:${o.playlistId}`)}`);
    await store.deleteRegistry(o.key);
    log.push(`${o.name}: deleted`);
  }
  return log;
}
